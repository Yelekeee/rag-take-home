"""Step 5: evaluation.

Runs every question in eval/questions.json through the system and saves, for
each one: the expected answer, the retrieved passages, the actual answer, and
a pass/fail judgment.

Output:  eval/results.json  (complete data)
         eval/results.md    (the same, easy to read)

Usage:  python3 evaluate.py
"""

import json
from pathlib import Path

import rag

EVAL_DIR = Path(__file__).parent / "eval"


def contains_all(text, phrases):
    return all(phrase.lower() in text.lower() for phrase in phrases)


def judge(test, result):
    """Decide pass or fail, and say why in one sentence.

    Answerable question:   pass if the system answered and the answer contains
                           every phrase listed in "must_contain".
    Unanswerable question: pass if the system declined to answer.
    """
    if not test["answerable"]:
        if result["answered"]:
            return False, "Should have declined, but gave an answer the documents do not support."
        return True, "Correctly declined to answer."

    if not result["answered"]:
        return False, "Declined, although the documents contain the answer."
    if contains_all(result["answer"], test["must_contain"]):
        return True, "The answer contains the expected fact."

    # Wrong answer. Say whether the right passage was at least retrieved.
    for rank, passage in enumerate(result["retrieved"], start=1):
        if contains_all(passage["text"], test["must_contain"]):
            return False, (f"Wrong answer. The right passage was retrieved at rank {rank} "
                           f"but was not the one used.")
    return False, "Wrong answer. The passage with the expected fact was not retrieved."


def write_markdown(records, path):
    passed = sum(record["passed"] for record in records)
    lines = [
        "# Evaluation results",
        "",
        f"**{passed} of {len(records)} passed.** Generated by `python3 evaluate.py`.",
        "",
        "| ID | Question | Should answer? | Did answer? | Result |",
        "|---|---|---|---|---|",
    ]
    for record in records:
        lines.append(
            f"| {record['id']} | {record['question']} "
            f"| {'yes' if record['answerable'] else 'no'} "
            f"| {'yes' if record['answered'] else 'no'} "
            f"| {'PASS' if record['passed'] else 'FAIL'} |"
        )

    for record in records:
        lines += [
            "",
            f"## {record['id']}: {record['question']}",
            "",
            f"- **Expected:** {record['expected']}",
            f"- **Actual answer:** {record['actual_answer']}",
            f"- **System's reason:** {record['system_reason']}",
        ]
        if record["cited_chunk"]:
            lines.append(f"- **Cited:** [{record['cited_chunk']}] {record['cited_url']}")
        lines += [
            f"- **Judgment:** {'PASS' if record['passed'] else 'FAIL'}. {record['judgment']}",
            "",
            "Retrieved passages:",
            "",
        ]
        if not record["retrieved"]:
            lines.append("(none)")
        for rank, passage in enumerate(record["retrieved"], start=1):
            lines.append(f"{rank}. `[{passage['chunk_id']}]` score {passage['score']}, "
                         f"coverage {passage['coverage']:.0%}: {passage['text']}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    tests = json.loads((EVAL_DIR / "questions.json").read_text(encoding="utf-8"))
    index = rag.build_index(rag.make_chunks(rag.load_documents()))

    records = []
    for test in tests:
        result = rag.answer_question(index, test["question"])
        passed, judgment = judge(test, result)
        citation = result["citation"] or {}
        records.append({
            "id": test["id"],
            "question": test["question"],
            "answerable": test["answerable"],
            "expected": test["expected"],
            "answered": result["answered"],
            "actual_answer": result["answer"],
            "system_reason": result["reason"],
            "cited_chunk": citation.get("chunk_id"),
            "cited_url": citation.get("url"),
            "retrieved": [
                {key: passage[key] for key in ("chunk_id", "score", "coverage", "url", "text")}
                for passage in result["retrieved"]
            ],
            "passed": passed,
            "judgment": judgment,
        })
        print(f"{test['id']}  {'PASS' if passed else 'FAIL'}  {test['question']}")
        print(f"      {judgment}")

    (EVAL_DIR / "results.json").write_text(
        json.dumps(records, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_markdown(records, EVAL_DIR / "results.md")

    passed = sum(record["passed"] for record in records)
    print(f"\n{passed} of {len(records)} passed. Details: eval/results.md and eval/results.json")


if __name__ == "__main__":
    main()
